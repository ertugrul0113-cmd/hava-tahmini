// Değeri renge çevir: [r,g,b,a 0-255]. NaN -> şeffaf.
export function renkBul(olcek, deger) {
  if (deger == null || Number.isNaN(deger)) return [0, 0, 0, 0];
  if (deger <= olcek[0][0]) return dur(olcek[0]);
  const son = olcek[olcek.length - 1];
  if (deger >= son[0]) return dur(son);
  for (let i = 1; i < olcek.length; i++) {
    const b = olcek[i];
    if (deger <= b[0]) {
      const a = olcek[i - 1];
      const k = (deger - a[0]) / (b[0] - a[0]);
      return [
        Math.round(a[1] + (b[1] - a[1]) * k),
        Math.round(a[2] + (b[2] - a[2]) * k),
        Math.round(a[3] + (b[3] - a[3]) * k),
        Math.round((a[4] + (b[4] - a[4]) * k) * 255)
      ];
    }
  }
  return dur(son);
}
function dur(d) { return [d[1], d[2], d[3], Math.round(d[4] * 255)]; }

// Hızlı çizim için tablo: 1024 adımlık renk dizisi.
export function renkTablosu(olcek) {
  const min = olcek[0][0], max = olcek[olcek.length - 1][0];
  const N = 1024;
  const tablo = new Uint8ClampedArray(N * 4);
  for (let i = 0; i < N; i++) {
    const c = renkBul(olcek, min + (max - min) * i / (N - 1));
    tablo.set(c, i * 4);
  }
  return { tablo, min, max, N };
}
